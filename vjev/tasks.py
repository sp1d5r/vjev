"""Each dataset as a set of typed questions, so one model can train on any mix of them.

A task turns an index row plus its decoded clip into an `Item`: a Jev record, the frame rate,
whether to pass audio, and one target per question. Targets are a level index for `score`
and `noul` questions, and a distribution over time bins for `moment` questions.

    snapugc  ecr (score, 10 levels)                         SnapUGC retention
    vf       5 scores, 1 to 4                               VideoFeedback, AI-video quality
    gv       ai_generated (noul)                            GenVideo, real or generated
    qv       moment (moment, one option per 2 s)            QVHighlights, text-query moments
    fq       moment (moment, one option per 1 s)            FunQA, funny / creative / magic moment
    vfai     ai_generated (noul) on VideoFeedback clips     cross-dataset test for gv
    vs       sound (choice, 8 people sounds)                VGGSound, the clean audio test
    fqc      FunQA creative moments only                    held-out question family (G4)
    vsl      laughing (noul) on VGGSound clips              a question never trained on (G4)
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

import numpy as np

from vjev.questions import VF_QUESTIONS, record_for, vf_record

# Decode settings per task: (fps, uses audio). They must match how the clips were decoded.
TASKS = {"snapugc": (2.0, True), "vf": (8.0, False), "gv": (8.0, False), "qv": (1.0, True),
         "fq": (2.0, True), "vfai": (8.0, False), "vs": (2.0, True), "fqc": (2.0, True),
         "vsl": (2.0, True)}
# Tasks that reuse another task's index: vfai asks GenVideo's question of VideoFeedback clips.
INDEX_OF = {"vfai": "vf", "fqc": "fq", "vsl": "vs"}
# G4 holds out FunQA's creative moments (C1) from training and asks them as `fqc`.
HELD_OUT_KIND = "C1"
LAUGH = {"people belly laughing", "people giggling", "baby laughter"}


def keep(task: str, rec: dict, held_out: bool) -> bool:
    """Whether an index row belongs to `task`. With held_out, `fq` drops the creative clips."""
    if task == "fqc":
        return rec["kind"] == HELD_OUT_KIND
    if task == "fq" and held_out:
        return rec["kind"] != HELD_OUT_KIND
    return True
# Real-or-AI tasks see the same length, shape and size for every clip. In GenVideo every real
# clip is 640x360, 24 fps and 10 s, and every generated clip is shorter and differently sized,
# so without this the answer can be read off the clip length or aspect ratio.
MATCHED = {"gv", "vfai"}
MATCHED_FRAMES = 12  # 1.5 s at 8 fps; the shortest generated clips are 1.6 s
MATCHED_SIDE = 256


def prepare_frames(task: str, frames: np.ndarray) -> np.ndarray:
    if task not in MATCHED:
        return frames
    from PIL import Image

    f = frames[:MATCHED_FRAMES]
    if len(f) < MATCHED_FRAMES:  # pad short clips by holding the last frame
        f = np.concatenate([f, np.repeat(f[-1:], MATCHED_FRAMES - len(f), axis=0)])
    h, w = f.shape[1:3]
    side = min(h, w)
    top, left = (h - side) // 2, (w - side) // 2
    f = f[:, top:top + side, left:left + side]
    return np.stack([np.asarray(Image.fromarray(x).resize((MATCHED_SIDE, MATCHED_SIDE),
                                                          Image.BICUBIC)) for x in f])

AI_QUESTION = {
    "type": "noul",
    "instructions": ("Was this video generated by an AI model, rather than filmed with a real "
                     "camera? Look at textures, motion, hands and faces, text, lighting and "
                     "physics."),
    "criteria": {"true": "AI-generated", "false": "real camera footage"},
}


@dataclass
class Item:
    record: dict
    fps: float
    audio: bool
    targets: dict[str, Any]       # question -> level index, or a distribution for moments
    kinds: dict[str, str]         # question -> score | noul | moment
    extra: dict[str, dict] = field(default_factory=dict)  # question -> data for metrics
    task: str = ""


def task_of(rec: dict, default: str) -> str:
    return rec.get("task", default)


def make_item(task: str, rec: dict, n_frames: int, duration: float, edges: list[float],
              audio: bool = True, wording_mode: str = "canonical", rng=None) -> Item:
    """wording_mode: canonical, train (random trained rewording) or heldout (unseen rewording),
    see `vjev/wordings.py`."""
    import copy

    from vjev.wordings import wording

    item = _make_item(task, rec, n_frames, duration, edges, audio)
    item.task = task
    if wording_mode != "canonical":
        item.record = copy.deepcopy(item.record)
        for q, question in item.record["questions"].items():
            text = wording(task, q, rec, wording_mode, rng)
            if text:
                question["instructions"] = text
    return item


def _make_item(task: str, rec: dict, n_frames: int, duration: float, edges: list[float],
               audio: bool) -> Item:
    fps, has_audio = TASKS[task]
    use_audio = has_audio and audio
    if task == "snapugc":
        from vjev.metrics import ecr_level

        level = int(ecr_level(np.array([rec["ecr"]]), np.array(edges))[0])
        return Item(record_for(rec, edges, duration, text=True), fps, use_audio,
                    {"ecr": level}, {"ecr": "score"},
                    {"ecr": {"raw": rec["ecr"], "edges": edges}})
    if task == "vf":
        return Item(vf_record(rec, duration), fps, use_audio,
                    {k: rec["scores"][k] - 1 for k in VF_QUESTIONS},
                    dict.fromkeys(VF_QUESTIONS, "score"),
                    {k: {"raw": rec["scores"][k] - 1, "edges": [0.5, 1.5, 2.5]}
                     for k in VF_QUESTIONS})
    if task in ("gv", "vfai"):  # no duration in the state: it gives the answer away
        record = {"state": {}, "questions": {"ai_generated": AI_QUESTION}}
        # noul options are ordered (true, false), so index 0 means AI-generated.
        return Item(record, fps, use_audio, {"ai_generated": 0 if not rec["real"] else 1},
                    {"ai_generated": "noul"}, {"ai_generated": {"group": rec.get("generator", "vf")}})
    if task == "qv":
        from vjev.model import moment_bins

        bins = moment_bins(n_frames, fps)
        record = {"state": {"duration_seconds": round(duration, 1)},
                  "questions": {"moment": {
                      "type": "moment",
                      "instructions": f'When does this happen in the video: "{rec["query"]}"?'}}}
        target, saliency = qv_target(rec, len(bins))
        return Item(record, fps, use_audio, {"moment": target}, {"moment": "moment"},
                    {"moment": {"saliency": saliency, "windows": rec["windows"],
                                "bin_s": bins[0][1] - bins[0][0] if bins else 2.0}})
    if task in ("fq", "fqc"):
        import hashlib

        from vjev.model import moment_bins

        bins = moment_bins(n_frames, fps)
        # One phrasing per clip, fixed by its id, so val and test are stable.
        k = int(hashlib.sha256(rec["id"].encode()).hexdigest(), 16) % len(rec["instructions"])
        record = {"state": {"duration_seconds": round(duration, 1)},
                  "questions": {"moment": {"type": "moment", "instructions": rec["instructions"][k]}}}
        return Item(record, fps, use_audio, {"moment": window_target(rec["windows"], bins)},
                    {"moment": "moment"},
                    {"moment": {"windows": rec["windows"],
                                "bin_s": bins[0][1] - bins[0][0] if bins else 1.0}})
    if task == "vs":
        from vjev.vggsound import CLASSES

        record = {"state": {}, "questions": {"sound": {
            "type": "choice",
            "instructions": "Which sound is most prominent in this clip?",
            "criteria": dict(CLASSES)}}}
        # choice options are sorted by key, so the target is the label's rank in that order.
        return Item(record, fps, use_audio, {"sound": sorted(CLASSES).index(rec["label"])},
                    {"sound": "choice"}, {"sound": {}})
    if task == "vsl":
        record = {"state": {}, "questions": {"laughing": {
            "type": "noul", "instructions": "Can you hear someone laughing in this clip?",
            "criteria": {"true": "yes, someone laughs", "false": "no laughter"}}}}
        return Item(record, fps, use_audio, {"laughing": 0 if rec["label"] in LAUGH else 1},
                    {"laughing": "noul"}, {"laughing": {}})
    raise ValueError(f"unknown task {task}")


def window_target(windows: list[list[float]], bins: list[tuple[float, float]]) -> list[float]:
    """Each bin weighted by how much of it the answer windows cover. A window shorter than a
    bin still marks the bin it falls in."""
    w = np.zeros(len(bins))
    for a, b in windows:
        for i, (t0, t1) in enumerate(bins):
            w[i] += max(0.0, min(b, t1) - max(a, t0))
        if w.sum() == 0 and bins:  # window past the decoded part: mark the last bin
            w[min(int(a // (bins[0][1] - bins[0][0])), len(bins) - 1)] = 1.0
    if w.sum() == 0:
        w = np.ones(max(1, len(bins)))
    return (w / w.sum()).tolist()


def qv_target(rec: dict, n_bins: int) -> tuple[list[float], list[list[float]]]:
    """Soft target: each relevant 2 s clip weighted by its mean highlight score. Also returns
    the per-annotator scores for every bin (0 outside the relevant clips), for HIT@1."""
    sal = [[0.0, 0.0, 0.0] for _ in range(n_bins)]
    for cid, s in zip(rec["clip_ids"], rec["saliency_scores"], strict=True):
        if cid < n_bins:
            sal[cid] = [float(x) for x in s]
    w = np.array([sum(s) / 3 for s in sal]) + 1e-3 * np.array(
        [1.0 if any(s) else 0.0 for s in sal])
    if w.sum() == 0:  # relevant clips all past the decoded window
        w = np.ones(n_bins)
    return (w / w.sum()).tolist(), sal


# ---------------------------------------------------------------- metrics


def binary_auc(score: np.ndarray, y: np.ndarray) -> float:
    from scipy.stats import rankdata

    pos, neg = y.sum(), (1 - y).sum()
    if pos == 0 or neg == 0:
        return float("nan")
    r = rankdata(score)
    return float((r[y == 1].sum() - pos * (pos + 1) / 2) / (pos * neg))


def noul_report(probs: np.ndarray, target: np.ndarray) -> dict:
    from vjev import metrics

    p_true = probs[:, 0]
    y = (target == 0).astype(int)
    auc = binary_auc(p_true, y)
    return {"auc": auc, "acc": float(((p_true > 0.5) == y).mean()),
            "brier": metrics.brier(probs, target), "ece": metrics.ece(probs, target),
            "final": auc, "n": len(target)}


def _span(p: np.ndarray, frac: float = 0.5) -> tuple[int, int]:
    """Contiguous bins around the peak whose probability is at least frac of the peak."""
    k = int(p.argmax())
    lo = hi = k
    while lo > 0 and p[lo - 1] >= frac * p[k]:
        lo -= 1
    while hi < len(p) - 1 and p[hi + 1] >= frac * p[k]:
        hi += 1
    return lo, hi + 1


def _iou(a: tuple[float, float], b: tuple[float, float]) -> float:
    inter = max(0.0, min(a[1], b[1]) - max(a[0], b[0]))
    union = max(a[1], b[1]) - min(a[0], b[0])
    return inter / union if union > 0 else 0.0


def _candidates(p: np.ndarray, bin_s: float, k: int = 10) -> list[tuple[float, float, float]]:
    """Ranked (start, end, score) spans: one per local peak, grown to bins at 50% of that
    peak, scored by the probability inside. Overlapping spans are dropped (IoU > 0.7)."""
    peaks = [i for i in range(len(p))
             if (i == 0 or p[i] >= p[i - 1]) and (i == len(p) - 1 or p[i] >= p[i + 1])]
    out: list[tuple[float, float, float]] = []
    for i in sorted(peaks, key=lambda j: -p[j]):
        lo = hi = i
        while lo > 0 and p[lo - 1] >= 0.5 * p[i]:
            lo -= 1
        while hi < len(p) - 1 and p[hi + 1] >= 0.5 * p[i]:
            hi += 1
        span = (lo * bin_s, (hi + 1) * bin_s, float(p[lo:hi + 1].sum()))
        if all(_iou(span[:2], c[:2]) <= 0.7 for c in out):
            out.append(span)
        if len(out) == k:
            break
    return sorted(out, key=lambda c: -c[2])


def _ap(preds: list[tuple[int, float, float, float]], gts: dict[int, list], thr: float) -> float:
    """ActivityNet-style average precision pooled over all queries, as QVHighlights uses."""
    n_gt = sum(len(v) for v in gts.values())
    used = {q: [False] * len(v) for q, v in gts.items()}
    tp = []
    for q, a, b, _ in sorted(preds, key=lambda x: -x[3]):
        ious = [_iou((a, b), tuple(w)) for w in gts[q]]
        j = int(np.argmax(ious)) if ious else -1
        if j >= 0 and ious[j] >= thr and not used[q][j]:
            used[q][j] = True
            tp.append(1)
        else:
            tp.append(0)
    tp = np.array(tp)
    if n_gt == 0 or len(tp) == 0:
        return 0.0
    ctp = np.cumsum(tp)
    prec = ctp / np.arange(1, len(tp) + 1)
    rec = ctp / n_gt
    # interpolated: precision envelope, integrated over recall steps
    prec = np.concatenate([[0], prec, [0]])
    rec = np.concatenate([[0], rec, [1]])
    for i in range(len(prec) - 2, -1, -1):
        prec[i] = max(prec[i], prec[i + 1])
    idx = np.where(rec[1:] != rec[:-1])[0] + 1
    return float(np.sum((rec[idx] - rec[idx - 1]) * prec[idx]))


def moment_report(probs: list[np.ndarray], extras: list[dict]) -> dict:
    """HIT@1 as in QVHighlights: the top bin is a hit for an annotator who rated it 4 (Very
    Good); averaged over the three annotators. R1@IoU uses the span around the peak."""
    hits, r5, r7, mass, ious = [], [], [], [], []
    for p, ex in zip(probs, extras, strict=True):
        k, bs = int(p.argmax()), ex["bin_s"]
        if "saliency" in ex:
            hits.append(np.mean([s == 4 for s in ex["saliency"][k]]))
            rel = np.array([any(s) for s in ex["saliency"]])
        else:  # no per-clip ratings: a hit is a peak bin that overlaps an answer window
            rel = np.array([any(min(b, (i + 1) * bs) > max(a, i * bs) for a, b in ex["windows"])
                            for i in range(len(p))])
            hits.append(float(rel[k]))
        lo, hi = _span(p)
        pred = (lo * bs, hi * bs)
        best = max((_iou(pred, tuple(w)) for w in ex["windows"]), default=0.0)
        ious.append(best)
        r5.append(best >= 0.5)
        r7.append(best >= 0.7)
        mass.append(float(p[rel].sum()) if rel.any() else 0.0)
    hit = float(np.mean(hits))
    preds = [(i, a, b, sc) for i, (p, ex) in enumerate(zip(probs, extras, strict=True))
             for a, b, sc in _candidates(p, ex["bin_s"])]
    gts = {i: ex["windows"] for i, ex in enumerate(extras)}
    aps = {t: _ap(preds, gts, t) for t in np.round(np.arange(0.5, 0.96, 0.05), 2)}
    return {"hit1": hit, "r1_05": float(np.mean(r5)), "r1_07": float(np.mean(r7)),
            "miou": float(np.mean(ious)), "mass_in_moment": float(np.mean(mass)),
            "map_05": aps[0.5], "map_075": aps[0.75], "map_avg": float(np.mean(list(aps.values()))),
            "final": hit, "n": len(probs)}


def score_report(probs: list[np.ndarray], extras: list[dict]) -> dict:
    from vjev import metrics

    p = np.array(probs)
    expected = p @ np.arange(p.shape[1])
    raw = np.array([e["raw"] for e in extras])
    r = metrics.report(expected, p, raw, np.array(extras[0]["edges"]))
    r["expected_std"] = float(expected.std())
    return r


def choice_report(probs: np.ndarray, target: np.ndarray) -> dict:
    from vjev import metrics

    acc = float((probs.argmax(1) == target).mean())
    return {"acc": acc, "brier": metrics.brier(probs, target), "ece": metrics.ece(probs, target),
            "final": acc, "n": len(target)}


def question_report(kind: str, probs: list[np.ndarray], targets: list, extras: list[dict]) -> dict:
    if kind == "choice":
        return choice_report(np.array(probs), np.array(targets))
    if kind == "score":
        return score_report(probs, extras)
    if kind == "noul":
        return noul_report(np.array(probs), np.array(targets))
    return moment_report(probs, extras)
