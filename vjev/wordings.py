# FunQA: training uses the dataset's own instructions; these are held out.
FQ_HELDOUT = {
    "H1": ["At what point in the video does the funniest thing happen?",
           "Which part of this clip makes people laugh?"],
    "C1": ["At what point does the most creative or inventive part of this video happen?",
           "Which part of this clip shows the clever, original idea?"],
    "M1": ["At what point does the magic trick happen in this video?",
           "Which part of this clip shows the illusion or trick?"],
}
WORDINGS[("vfai", "ai_generated")] = WORDINGS[("gv", "ai_generated")]


def _pick(options: list[str], key: str) -> str:
    return options[int(hashlib.sha256(key.encode()).hexdigest(), 16) % len(options)]


def wording(task: str, q: str, rec: dict, mode: str, rng: random.Random | None = None) -> str | None:
    """New instructions for question q, or None to keep the canonical ones.
    mode: canonical (no change), train (random over the trained wordings), heldout (one of
    the unseen wordings, fixed per clip)."""
    if mode == "canonical":
        return None
    rng = rng or random.Random()
    base = "fq" if task in ("fq", "fqc") else task
    if base == "fq":
        if mode == "train":
            return rng.choice(rec["instructions"])
        return _pick(FQ_HELDOUT[rec["kind"]], rec["id"])
    options = WORDINGS.get((base, q))
    if not options:
        return None
    pool = options[:N_TRAIN] if mode == "train" else options[N_TRAIN:]
    text = rng.choice(pool) if mode == "train" else _pick(pool, rec["id"])
    return text.format(query=rec["query"]) if "{query}" in text else text
